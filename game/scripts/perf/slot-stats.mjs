// Writes shared/slot-stats.js: for every model slot in the manifest, its
// height, whether it's inked, two-sided or glows through a mask, and per
// variant how many triangles it has (and how many of them are two-sided).
// The budget estimator (shared/budget.js) reads it, so the world editor can
// say what a chunk will cost without loading any models. Run it after
// changing the manifest: node scripts/perf/slot-stats.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { MODELS } from '../../client/src/scene/manifest/index.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const PUBLIC = path.join(ROOT, 'client', 'public');

// The JSON part of a .glb file.
function gltfJson(file) {
  const buf = fs.readFileSync(file);
  if (buf.readUInt32LE(0) !== 0x46546c67) throw new Error(`${file} is not a .glb`);
  const len = buf.readUInt32LE(12);
  return JSON.parse(buf.subarray(20, 20 + len).toString('utf8'));
}

function stats(file) {
  const g = gltfJson(file);
  let one = 0;
  let two = 0;
  let y0 = Infinity;
  let y1 = -Infinity;
  // Every mesh as many times as nodes use it.
  const uses = new Map();
  for (const n of g.nodes ?? []) if (n.mesh != null) uses.set(n.mesh, (uses.get(n.mesh) ?? 0) + 1);
  (g.meshes ?? []).forEach((m, i) => {
    for (const p of m.primitives) {
      const acc = g.accessors[p.indices ?? p.attributes.POSITION];
      const tris = Math.round((p.indices != null ? acc.count : acc.count) / 3) * (uses.get(i) ?? 1);
      if (g.materials?.[p.material]?.doubleSided) two += tris;
      else one += tris;
      const pos = g.accessors[p.attributes.POSITION];
      if (pos.min) (y0 = Math.min(y0, pos.min[1])), (y1 = Math.max(y1, pos.max[1]));
    }
  });
  return { one, two, h: Number.isFinite(y1 - y0) ? y1 - y0 : 1 };
}

const out = {};
for (const [slot, def] of Object.entries(MODELS)) {
  if (!def?.url) continue;
  const urls = [].concat(def.url);
  const v = [];
  let rawH = 1;
  for (const u of urls) {
    const file = path.join(PUBLIC, u);
    if (!fs.existsSync(file)) continue;
    const s = stats(file);
    rawH = s.h;
    v.push({ tris: s.one + s.two, double: s.two });
  }
  if (!v.length) continue;
  const h = def.height ?? (def.scale ? rawH * def.scale : rawH);
  out[slot] = { h: Math.round(h * 100) / 100, ink: def.outline !== false, double: !!def.doubleSide, ...(def.glowBand ? { glow: true } : {}), v };
}
const file = path.join(ROOT, 'shared', 'slot-stats.js');
fs.writeFileSync(file, `// Generated by scripts/perf/slot-stats.mjs from the model files: per model slot,\n// its height (m), whether it's inked and two-sided, and per variant its triangles.\nexport default ${JSON.stringify(out)};\n`);
console.log(`${path.relative(ROOT, file)}: ${Object.keys(out).length} slots`);
